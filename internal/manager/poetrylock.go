package manager

import (
	"bufio"
	"bytes"
	"path/filepath"
	"regexp"

	"github.com/KazuyaMiyagi/list-versions/internal/entry"
)

var poetryLockHeaderRe = regexp.MustCompile(`^# This file is automatically @generated by Poetry (\S+) and`)

// PoetryLockTool reads the Poetry version recorded in the comment Poetry
// writes at the top of poetry.lock, the counterpart of `BUNDLED WITH` in
// Gemfile.lock. The packages in the lock are handled by PoetryLock under
// --deps.
type PoetryLockTool struct{}

func (PoetryLockTool) Name() string { return "poetry-lock-tool" }

func (PoetryLockTool) Match(path string) bool { return filepath.Base(path) == "poetry.lock" }

func (PoetryLockTool) Extract(file File) ([]entry.Entry, error) {
	data, err := readBytes(file)
	if err != nil {
		return nil, err
	}
	scanner := bufio.NewScanner(bytes.NewReader(data))
	if !scanner.Scan() {
		return nil, scanner.Err()
	}
	m := poetryLockHeaderRe.FindStringSubmatch(scanner.Text())
	if m == nil {
		return nil, nil
	}
	return []entry.Entry{{
		Type:    "Poetry",
		Path:    filepath.Dir(file.Path),
		Name:    "poetry.lock",
		Version: m[1],
	}}, nil
}
