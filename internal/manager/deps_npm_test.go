func TestPackageJSONDeps(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "package.json"), `{
  "name": "x",
  "dependencies": {"react": "^18.2.0", "@types/node": "^20.0.0"},
  "devDependencies": {"vitest": "^1.0.0"}
}`)
	es := collect(t, PackageJSONDeps{}, dir)
	got := map[string]string{}
	gotName := map[string]string{}
	for _, e := range es {
		got[e.Type] = e.Version
		gotName[e.Type] = e.Name
	}
	want := map[string]string{
		"npm:react":       "^18.2.0",
		"npm:@types/node": "^20.0.0",
		"npm:vitest":      "^1.0.0",
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s: got %q, want %q", k, got[k], v)
		}
	}
	if gotName["npm:react"] != "package.json" {
		t.Errorf("prod dep Name: got %q, want %q", gotName["npm:react"], "package.json")
	}
	if gotName["npm:vitest"] != "package.json (dev)" {
		t.Errorf("dev dep Name: got %q, want %q", gotName["npm:vitest"], "package.json (dev)")
	}
}

func TestPackageLockJSON_V3(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "package-lock.json"), `{
  "name": "x",
  "lockfileVersion": 3,
  "packages": {
    "": {
      "dependencies": {"react": "^18.2.0"},
      "devDependencies": {"vitest": "^1.0.0"}
    },
    "node_modules/react": {"version": "18.3.1"},
    "node_modules/vitest": {"version": "1.2.0", "dev": true},
    "node_modules/transitive": {"version": "9.9.9"}
  }
}`)
	es := collect(t, PackageLockJSON{}, dir)
	got := map[string]string{}
	gotName := map[string]string{}
	for _, e := range es {
		got[e.Type] = e.Version
		gotName[e.Type] = e.Name
	}
	if got["npm:react"] != "18.3.1" {
		t.Errorf("react: got %q, want 18.3.1", got["npm:react"])
	}
	if got["npm:vitest"] != "1.2.0" {
		t.Errorf("vitest: got %q, want 1.2.0", got["npm:vitest"])
	}
	// Transitive deps are emitted too: the lockfile pins what's actually
	// installed, which is what you want for vulnerability hunting.
	if got["npm:transitive"] != "9.9.9" {
		t.Errorf("transitive dep should be included, got %v", got)
	}
	if gotName["npm:react"] != "package-lock.json" {
		t.Errorf("prod dep Name: got %q", gotName["npm:react"])
	}
	if gotName["npm:vitest"] != "package-lock.json (dev)" {
		t.Errorf("dev dep Name: got %q", gotName["npm:vitest"])
	}
}

