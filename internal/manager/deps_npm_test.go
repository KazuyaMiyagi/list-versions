func TestBunLock(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "bun.lock"), `{
  "lockfileVersion": 1,
  "workspaces": {
    "": { "name": "my-app", "dependencies": ["bar@^1.0.0"] }
  },
  "packages": {
    "react": ["react@18.3.1", {}, "sha512-..."],
    "@types/node": ["@types/node@20.11.5", {}, "sha512-..."],
    "forked": ["forked@git+ssh://git@github.com/x/y.git#abc", {}]
  }
}`)
	es := collect(t, BunLock{}, dir)
	got := map[string]string{}
	for _, e := range es {
		got[e.Type] = e.Version
	}
	want := map[string]string{
		"npm:react":       "18.3.1",
		"npm:@types/node": "20.11.5",
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s: got %q, want %q", k, got[k], v)
		}
	}
	for k, v := range got {
		if strings.Contains(k, "://") || strings.Contains(k, "git+") {
			t.Errorf("URL spec leaked through as type: %q", k)
		}
		if strings.Contains(v, "://") || strings.Contains(v, "git+") || strings.Contains(v, "github.com") {
			t.Errorf("URL spec leaked through as version: %s = %q", k, v)
		}
	}
	if _, ok := got["npm:forked"]; ok {
		t.Errorf("URL-based dep `forked` should be skipped, got %v", got)
	}
	if _, ok := got["npm:my-app"]; ok {
		t.Errorf("workspace name should not be parsed as a dependency")
	}
}
