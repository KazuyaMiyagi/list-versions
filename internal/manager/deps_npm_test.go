func TestYarnLock(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "yarn.lock"), `# THIS IS AN AUTOGENERATED FILE
# yarn lockfile v1


"react@^18.2.0":
  version "18.3.1"
  resolved "https://..."

"@types/node@^20.0.0", "@types/node@^20.10.0":
  version "20.11.5"

vitest@^1.0.0:
  version "1.2.0"

"forked-dep@git+ssh://git@github.com/x/y.git#abc":
  version "1.2.3"
`)
	es := collect(t, YarnLock{}, dir)
	got := map[string]string{}
	for _, e := range es {
		got[e.Type] = e.Version
	}
	want := map[string]string{
		"npm:react":       "18.3.1",
		"npm:@types/node": "20.11.5",
		"npm:vitest":      "1.2.0",
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s: got %q, want %q", k, got[k], v)
		}
	}
	// URL specs split incorrectly with LastIndex('@'); don't emit garbage.
	for k := range got {
		if strings.Contains(k, "://") || strings.Contains(k, "git+") {
			t.Errorf("URL spec leaked through: %q", k)
		}
	}
}

// TestYarnLock_Berry covers Yarn v2+ (Berry) lockfiles, whose `version:` lines
// use a colon and unquoted value, and whose keys use the `@npm:` protocol. The
// leading `__metadata` block (with its own `version:`) must not be mistaken for
// a package.
func TestYarnLock_Berry(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "yarn.lock"), `# This file is generated by running "yarn install"

__metadata:
  version: 8
  cacheKey: 10c0

"react@npm:^18.2.0":
  version: 18.3.1
  resolution: "react@npm:18.3.1"

"@types/node@npm:^20.0.0, @types/node@npm:^20.10.0":
  version: "20.11.5"
  resolution: "@types/node@npm:20.11.5"

"forked@npm:git+ssh://git@github.com/x/y.git#abc":
  version: 1.2.3
`)
	es := collect(t, YarnLock{}, dir)
	got := map[string]string{}
	for _, e := range es {
		got[e.Type] = e.Version
	}
	want := map[string]string{
		"npm:react":       "18.3.1",
		"npm:@types/node": "20.11.5",
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s: got %q, want %q", k, got[k], v)
		}
	}
	if _, ok := got["npm:__metadata"]; ok {
		t.Errorf("__metadata block leaked through as a package: %v", got)
	}
	for k := range got {
		if strings.Contains(k, "://") || strings.Contains(k, "git+") {
			t.Errorf("URL spec leaked through: %q", k)
		}
	}
}

