package manager

import (
	"path/filepath"
	"reflect"
	"testing"
)

func TestPoetryLockTool(t *testing.T) {
	cases := []struct {
		name string
		body string
		want []string
	}{
		{"generated header", "# This file is automatically @generated by Poetry 1.8.3 and should not be changed by hand.\n", []string{"1.8.3"}},
		{"header without a version skipped", "# This file is automatically @generated by Poetry and should not be changed by hand.\n", nil},
		{"no header", "", nil},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			dir := t.TempDir()
			writeFile(t, filepath.Join(dir, "poetry.lock"), c.body+"\n[[package]]\nname = \"requests\"\nversion = \"2.32.3\"\n")
			var got []string
			for _, e := range collect(t, PoetryLockTool{}, dir) {
				if e.Type != "Poetry" || e.Name != "poetry.lock" {
					t.Errorf("got %+v, want Type Poetry from poetry.lock", e)
				}
				got = append(got, e.Version)
			}
			if !reflect.DeepEqual(got, c.want) {
				t.Errorf("got %v, want %v", got, c.want)
			}
		})
	}
}
